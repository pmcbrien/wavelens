#!/usr/bin/env python3
"""
Writes the bridge's band table (BANDS and GNSS in ../pi/wavelens_bridge.py) into the companion page
and README, so the published list is always what the code does. Run after changing BANDS:

    python3 companion/tools/band_table.py          # from the repo root

Rows keep the bridge's own order and section headings, because the bridge uses the first range in
the list that contains a frequency: where ranges overlap, the earlier row wins.
"""
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
BRIDGE = ROOT / "companion/pi/wavelens_bridge.py"
PAGE = ROOT / "site/companion.html"
README = ROOT / "companion/README.md"
START, END = "<!-- bands:start (generated by companion/tools/band_table.py) -->", "<!-- bands:end -->"

CAT = {
    "DRONE": "Drone / video link", "VEHICLE": "Vehicle", "IOT": "IoT / sensor", "PHONE": "Phone",
    "CAMERA": "Camera", "NETWORK": "Network", "TRAFFIC_SENSOR": "Traffic sensor", "CELL_SITE": "Cell site",
    "TOOL": "RF tool", "UNKNOWN": "Unclassified", "LE_GEAR": "LE gear",
}


def B(lo, hi, name, cat="UNKNOWN", conf="POSSIBLE", kind="", steady=None):
    return {"lo": lo, "hi": hi, "name": name, "cat": cat, "conf": conf, "kind": kind, "steady": steady}


def read_bands():
    """(section heading, [band, ...]) in the bridge's order, read from its source."""
    src = BRIDGE.read_text(encoding="utf-8")
    body = src[src.index("BANDS = [") + len("BANDS = ["):]
    body = body[: body.index("\n]")]
    sections, title, buf, depth, pending_note = [], "Bands", "", 0, ""
    for raw in body.splitlines():
        line = raw.strip()
        if not buf:
            m = re.match(r"#\s*-{3,}\s*(.+)", line)
            if m:
                title = m.group(1).split(":")[0].strip().rstrip("—").strip()
                title = title[0].upper() + title[1:]
                sections.append((title, []))
                continue
            if not line.startswith("B("):
                continue
        code, _, note = line.partition("  #")
        buf += " " + code
        if note and depth == 0:
            pending_note = note.strip()
        depth += code.count("(") - code.count(")")
        if depth <= 0:
            band = eval(buf.strip().rstrip(","), {"B": B})          # trusted: our own source file
            band["note"], pending_note = pending_note, ""
            if not sections:
                sections.append((title, []))
            sections[-1][1].append(band)
            buf, depth = "", 0
    return sections


def mhz(v):
    return f"{v:g}"


def span(b):
    return f"{mhz(b['lo'])}–{mhz(b['hi'])} MHz"


def how(b):
    if b["name"] is None:
        return "Not reported"
    if b["kind"] == "bg":
        return "Background: once a minute per band, never an alert"
    if b["steady"]:
        return f"Bursts as shown; a carrier still there after 3 passes becomes “{b['steady'][0]}”"
    if b["kind"] == "persist" or b["cat"] == "DRONE":
        return "Only when it's on two passes in a row"
    return "Each burst over the noise floor"


def html_table(sections):
    out = []
    for title, bands in sections:
        out.append(f'        <tr class="sec"><th colspan="4">{html.escape(title)}</th></tr>')
        for b in bands:
            label = html.escape(b["name"] or b.get("note") or "—")
            cat = CAT.get(b["cat"], b["cat"].title()) if b["name"] else ""
            out.append(f"        <tr><td>{span(b).replace(' MHz', '&nbsp;MHz')}</td><td>{label}</td>"
                       f"<td>{html.escape(cat)}</td><td>{html.escape(how(b))}</td></tr>")
    return "\n".join(out)


def md_table(sections):
    out = ["| Range | Reported as | Category | When |", "|---|---|---|---|"]
    for title, bands in sections:
        out.append(f"| **{title}** | | | |")
        for b in bands:
            cat = CAT.get(b["cat"], b["cat"].title()) if b["name"] else ""
            out.append(f"| {span(b)} | {b['name'] or b.get('note') or '—'} | {cat} | {how(b)} |")
    return "\n".join(out)


def replace_between(path: pathlib.Path, block: str) -> None:
    text = path.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit(f"{path}: markers missing ({START} … {END})")
    a, b = text.index(START) + len(START), text.index(END)
    path.write_text(text[:a] + "\n" + block + "\n" + text[b:], encoding="utf-8")


if __name__ == "__main__":
    secs = read_bands()
    n = sum(len(b) for _, b in secs)
    replace_between(PAGE, f"      <!-- {n} ranges -->\n      <table class=\"bands\">\n"
                          "        <tr><th>Range</th><th>Reported as</th><th>Category</th><th>When</th></tr>\n"
                          + html_table(secs) + "\n      </table>")
    replace_between(README, md_table(secs))
    print(f"{n} ranges in {len(secs)} sections → {PAGE.relative_to(ROOT)}, {README.relative_to(ROOT)}")
